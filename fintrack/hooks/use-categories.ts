import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import axiosClient from "@/lib/api/client";
import { saveToLocal, cacheResponse, getCachedResponse, mergePendingMutations, appendToCache } from "@/lib/offline/db";
import { useAuthStore } from "@/lib/zustand/auth-store";
import { toast } from "sonner";
import type { AxiosError } from "axios";

interface ErrorResponse {
    message: string;
}

export interface Category {
    id: string;
    userId: string;
    name: string;
    color: string;
    icon: string | null;
    type: 'EXPENSE' | 'INCOME';
    isAutoGenerated: boolean;
    createdAt: string;
    updatedAt: string;
}

export function useCategories() {
    const queryClient = useQueryClient();
    const { user } = useAuthStore();
    const userId = user?.id || "guest";

    const query = useQuery({
        queryKey: ['categories'],
        queryFn: async () => {
            try {
                const res = await axiosClient.get("/categories");
                const data = (res.data as Category[]) || [];
                await cacheResponse(userId, '/api/categories', data);
                const merged = await mergePendingMutations(userId, data, "/categories");
                return merged as Category[];
            } catch (error) {
                const cached = await getCachedResponse(userId, '/api/categories');
                if (cached) {
                    console.log('[Categories] Serving from offline cache');
                    const merged = await mergePendingMutations(userId, cached.data, "/categories");
                    return merged as Category[];
                }
                throw error;
            }
        },
        initialData: []
    });

    const createMutation = useMutation({
        mutationFn: async (data: { name: string, type: 'EXPENSE' | 'INCOME', icon?: string }) => {
            const record = await saveToLocal(userId, {
                action: "CREATE",
                data,
                endpoint: "/categories",
            });

            await appendToCache(userId, "/api/categories", "CREATE", {
                ...data,
                id: record.id,
                userId: "",
                color: "#6b7280",
                icon: data.icon || null,
                isAutoGenerated: false,
                createdAt: new Date().toISOString(),
                updatedAt: new Date().toISOString(),
                isOffline: !navigator.onLine,
            });

            if (navigator.onLine) {
                try {
                    const res = await axiosClient.post("/categories", data);
                    const { updateRecordStatus } = await import("@/lib/offline/db");
                    await updateRecordStatus(userId, record.id, "synced");
                    return res.data;
                } catch {
                    return { ...data, id: record.id, isPending: true } as any;
                }
            }

            return { ...data, id: record.id, isPending: true } as any;
        },
        onMutate: async (newCategory) => {
            await queryClient.cancelQueries({ queryKey: ['categories'] });
            const previousCategories = queryClient.getQueryData(['categories']);

            const optimisticCategory = {
                id: `temp_${Date.now()}`,
                name: newCategory.name,
                type: newCategory.type,
                icon: newCategory.icon || null,
                color: "#6b7280",
                userId: "",
                isAutoGenerated: false,
                createdAt: new Date().toISOString(),
                updatedAt: new Date().toISOString(),
                isOffline: !navigator.onLine,
            };

            queryClient.setQueryData(['categories'], (old: any) => {
                if (!old) return [optimisticCategory];
                return [...old, optimisticCategory];
            });

            return { previousCategories };
        },
        onSuccess: (data) => {
            if (data && (data as any).isPending) {
                // Silent success for offline
            } else {
                queryClient.invalidateQueries({ queryKey: ['categories'] });
            }
        },
        onError: (error, _, context) => {
            if (context?.previousCategories) {
                queryClient.setQueryData(['categories'], context.previousCategories);
            }
        }
    });

    const updateCategory = useMutation({
        mutationFn: async ({ id, data }: { id: string, data: { name?: string, color?: string, icon?: string } }) => {
            const record = await saveToLocal(userId, {
                action: "UPDATE",
                data: { id, ...data },
                endpoint: `/categories/${id}`,
            });

            await appendToCache(userId, "/api/categories", "UPDATE", { id, ...data });

            if (navigator.onLine) {
                try {
                    const res = await axiosClient.put(`/categories/${id}`, data);
                    const { updateRecordStatus } = await import("@/lib/offline/db");
                    await updateRecordStatus(userId, record.id, "synced");
                    return res.data;
                } catch {
                    return { ...data, id, isPending: true } as any;
                }
            }

            return { ...data, id, isPending: true } as any;
        },
        onMutate: async ({ id, data }) => {
            await queryClient.cancelQueries({ queryKey: ['categories'] });
            const previousCategories = queryClient.getQueryData(['categories']);

            queryClient.setQueryData(['categories'], (old: any) => {
                if (!old) return old;
                return old.map((cat: any) =>
                    cat.id === id ? { ...cat, ...data, isOffline: !navigator.onLine } : cat
                );
            });

            return { previousCategories };
        },
        onSuccess: (data) => {
            if (data && (data as any).isPending) {
                toast.success("Kategori diperbarui secara offline!");
            } else {
                queryClient.invalidateQueries({ queryKey: ['categories'] });
                toast.success("Kategori berhasil diperbarui");
            }
        },
        onError: (error: AxiosError<ErrorResponse>, _, context) => {
            if (context?.previousCategories) {
                queryClient.setQueryData(['categories'], context.previousCategories);
            }
            toast.error(error.response?.data?.message || "Gagal memperbarui kategori");
        }
    });

    const deleteCategory = useMutation({
        mutationFn: async (id: string) => {
            const record = await saveToLocal(userId, {
                action: "DELETE",
                data: { id },
                endpoint: `/categories/${id}`,
            });

            await appendToCache(userId, "/api/categories", "DELETE", { id });

            if (navigator.onLine) {
                try {
                    await axiosClient.delete(`/categories/${id}`);
                    const { updateRecordStatus } = await import("@/lib/offline/db");
                    await updateRecordStatus(userId, record.id, "synced");
                    return { id };
                } catch {
                    return { id, isPending: true };
                }
            }

            return { id, isPending: true };
        },
        onMutate: async (id) => {
            await queryClient.cancelQueries({ queryKey: ['categories'] });
            const previousCategories = queryClient.getQueryData(['categories']);

            queryClient.setQueryData(['categories'], (old: any) => {
                if (!old) return old;
                return old.filter((cat: any) => cat.id !== id);
            });

            return { previousCategories };
        },
        onSuccess: (data) => {
            if (data && (data as any).isPending) {
                toast.success("Kategori dihapus secara offline!");
            } else {
                queryClient.invalidateQueries({ queryKey: ['categories'] });
                toast.success("Kategori berhasil dihapus");
            }
        },
        onError: (error: AxiosError<ErrorResponse>, _, context) => {
            if (context?.previousCategories) {
                queryClient.setQueryData(['categories'], context.previousCategories);
            }
            toast.error(error.response?.data?.message || "Gagal menghapus kategori");
        }
    });

    return {
        categories: query.data,
        isLoading: query.isLoading,
        error: query.error,
        createCategoryAsync: createMutation.mutateAsync,
        isCreating: createMutation.isPending,
        updateCategory,
        deleteCategory
    };
}
